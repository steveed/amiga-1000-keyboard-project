"""Generate the rev 2 firmware's keymap (firmware/src/keymap.h) from the rev 2 matrix.

    python tools/gen_keymap.py      (in the tools container)

The matrix comes from tools/gen_rev2_sch.py, the same code that draws the schematic, so the firmware
can't drift from the board.  Each key's Amiga raw key code and USB HID usage are looked up by its
name (the rev 1 schematic's switch values).
"""

import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from gen_rev2_sch import COLS, ROWS, matrix_map  # noqa: E402

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(REPO, 'firmware/src/keymap.h')

# name: (Amiga raw key code, USB HID usage).  Usages 0xE0-0xE7 are the modifiers; the firmware
# turns them into the report's modifier bits.  HELP has no common USB equivalent, so it sends the
# HID Help usage, as Henryk's A500KB does.
KEYS = {
    '`': (0x00, 0x35), '1': (0x01, 0x1E), '2': (0x02, 0x1F), '3': (0x03, 0x20), '4': (0x04, 0x21),
    '5': (0x05, 0x22), '6': (0x06, 0x23), '7': (0x07, 0x24), '8': (0x08, 0x25), '9': (0x09, 0x26),
    '0': (0x0A, 0x27), '-': (0x0B, 0x2D), '=': (0x0C, 0x2E), '\\': (0x0D, 0x31), 'KP 0': (0x0F, 0x62),
    'Q': (0x10, 0x14), 'W': (0x11, 0x1A), 'E': (0x12, 0x08), 'R': (0x13, 0x15), 'T': (0x14, 0x17),
    'Y': (0x15, 0x1C), 'U': (0x16, 0x18), 'I': (0x17, 0x0C), 'O': (0x18, 0x12), 'P': (0x19, 0x13),
    '[': (0x1A, 0x2F), ']': (0x1B, 0x30), 'KP 1': (0x1D, 0x59), 'KP 2': (0x1E, 0x5A), 'KP 3': (0x1F, 0x5B),
    'A': (0x20, 0x04), 'S': (0x21, 0x16), 'D': (0x22, 0x07), 'F': (0x23, 0x09), 'G': (0x24, 0x0A),
    'H': (0x25, 0x0B), 'J': (0x26, 0x0D), 'K': (0x27, 0x0E), 'L': (0x28, 0x0F), ';': (0x29, 0x33),
    "'": (0x2A, 0x34), '(RET) INTL': (0x2B, 0x32), 'KP 4': (0x2D, 0x5C), 'KP 5': (0x2E, 0x5D),
    'KP 6': (0x2F, 0x5E), 'L SHIFT INTL': (0x30, 0x64), 'Z': (0x31, 0x1D), 'X': (0x32, 0x1B),
    'C': (0x33, 0x06), 'V': (0x34, 0x19), 'B': (0x35, 0x05), 'N': (0x36, 0x11), 'M': (0x37, 0x10),
    ',': (0x38, 0x36), '.': (0x39, 0x37), '/': (0x3A, 0x38), 'KP .': (0x3C, 0x63), 'KP 7': (0x3D, 0x5F),
    'KP 8': (0x3E, 0x60), 'KP 9': (0x3F, 0x61), 'SPACE': (0x40, 0x2C), 'BACKSPACE': (0x41, 0x2A),
    'TAB': (0x42, 0x2B), 'KP ENTER': (0x43, 0x58), 'RETURN': (0x44, 0x28), 'ESC': (0x45, 0x29),
    'DEL': (0x46, 0x4C), 'KP -': (0x4A, 0x56), 'UP': (0x4C, 0x52), 'DOWN': (0x4D, 0x51),
    'RIGHT': (0x4E, 0x4F), 'LEFT': (0x4F, 0x50), 'HELP': (0x5F, 0x75),
    **{f'F{i}': (0x4F + i, 0x39 + i) for i in range(1, 11)},
    'L SHIFT': (0x60, 0xE1), 'R SHIFT': (0x61, 0xE5), 'CAPS LOCK': (0x62, 0x39), 'CTRL': (0x63, 0xE0),
    'L ALT': (0x64, 0xE2), 'R ALT': (0x65, 0xE6), 'L AMIGA': (0x66, 0xE3), 'R AMIGA': (0x67, 0xE7),
}

NONE = 0xFF


def main():
    cells, names = matrix_map()
    names = {ref: name.replace('\\\\', '\\') for ref, name in names.items()}   # KiCad escapes backslashes
    amiga = [[NONE] * len(COLS) for _ in ROWS]
    hid = [[0] * len(COLS) for _ in ROWS]
    label = [[''] * len(COLS) for _ in ROWS]
    for ref, (r, c) in cells.items():
        amiga[r][c], hid[r][c] = KEYS[names[ref]]
        label[r][c] = names[ref]
    codes = [a for row in amiga for a in row if a != NONE]
    assert len(codes) == len(set(codes)) == len(cells), 'two keys share an Amiga code'

    out = ['/* Generated by tools/gen_keymap.py from the rev 2 matrix - do not edit. */',
           '/* Include it in one .c file only, after defining KEYMAP_FLASH (PROGMEM on the AVR). */',
           '#ifndef KEYMAP_H', '#define KEYMAP_H', '', '#include <stdint.h>', '',
           f'#define KEYMAP_NONE 0x{NONE:02X}   /* no switch at this position */', '',
           f'/* rows: {", ".join(ROWS)} */', f'/* columns: {", ".join(COLS)} */', '']
    for title, var, table in (('Amiga raw key codes', 'keymap_amiga', amiga), ('USB HID usages', 'keymap_hid', hid)):
        out += [f'/* {title}, [row][column] */',
                f'static const uint8_t {var}[{len(ROWS)}][{len(COLS)}] KEYMAP_FLASH = {{']
        for r, row in enumerate(table):
            cols = ', '.join(f'0x{v:02X}' for v in row)
            out.append(f'    {{ {cols} }},   /* {", ".join(n or "-" for n in label[r])} */')
        out += ['};', '']
    out += ['#endif', '']
    with open(OUT, 'w') as f:
        f.write('\n'.join(out))
    print(f'wrote {os.path.relpath(OUT, REPO)}: {len(cells)} keys')


if __name__ == '__main__':
    main()
